"""de Bruijn--Newman family H_t(z) = int_0^inf exp(t u^2) Phi(u) cos(z u) du.

Phi(u) = sum_{n>=1} (2 pi^2 n^4 e^{9u} - 3 pi n^2 e^{5u}) exp(-pi n^2 e^{4u}).

Normalisation check: H_0(z) = (1/8) xi(1/2 + i z/2), xi(s) = s(s-1)/2 pi^{-s/2} Gamma(s/2) zeta(s),
so the zeros of H_0 are z = 2*gamma_k (gamma_k = ordinates of zeta zeros).

Quadrature.  Phi is even and analytic in |Im u| < pi/8 and decays like exp(-pi e^{4|u|}),
so the trapezoidal rule on the whole line converges geometrically; by evenness
    int_0^inf f(u) du  ~  h * ( f(0)/2 + sum_{k>=1} f(k h) ),  u_k = k h <= U.
The result for real z is exponentially small (~ e^{-pi z/8}) while the integrand is O(1),
so the sum is evaluated in high precision (mpmath).  For speed the sum is carried out in
Python-integer fixed point with 'prec' fractional bits (exact integer arithmetic, rounding
error ~ N * 2^-prec), and e^{i z u_k} is generated by repeated multiplication by e^{i z h}.

All z-derivatives and the z-antiderivative are available in closed form:
    d^j/dz^j H_t(z) = Re( i^j * sum_k W_k E_k(t) u_k^j e^{i z u_k} )
    F_t(z) := int_0^z H_t = W_0 E_0 z + sum_{k>=1} W_k E_k sin(z u_k)/u_k
    d^m/dt^m H_t = sum_k W_k E_k u_k^{2m} cos(z u_k)        (so d_t H = -d_z^2 H exactly here too)
"""
import mpmath as mp


def Phi(u, nmax=None):
    u = mp.mpf(u)
    e4 = mp.exp(4 * u)
    s = mp.mpf(0)
    n = 1
    tiny = mp.mpf(2) ** (-mp.mp.prec - 40)
    while True:
        n2 = n * n
        term = (2 * mp.pi ** 2 * n2 * n2 * mp.exp(9 * u) - 3 * mp.pi * n2 * mp.exp(5 * u)) * mp.exp(-mp.pi * n2 * e4)
        s += term
        if nmax is not None and n >= nmax:
            break
        if abs(term) < tiny * (abs(s) + tiny) and n > 2:
            break
        n += 1
    return s


class HFlow:
    def __init__(self, dps=80, h=mp.mpf(1) / 160, U=mp.mpf('1.25')):
        mp.mp.dps = dps
        self.dps = dps
        self.h = mp.mpf(h)
        self.U = mp.mpf(U)
        self.N = int(mp.floor(self.U / self.h)) + 1
        self.prec = mp.mp.prec + 30           # fixed-point fractional bits
        self.one = 1 << self.prec
        self.u = [k * self.h for k in range(self.N)]
        W = []
        for k, u in enumerate(self.u):
            w = self.h * Phi(u)
            if k == 0:
                w /= 2
            W.append(w)
        self.W = W
        self._tcache = {}

    def _fx(self, x):
        return int(mp.nint(mp.ldexp(x, self.prec)))

    def _weights(self, t):
        key = mp.nstr(mp.mpf(t), 50)
        if key not in self._tcache:
            t = mp.mpf(t)
            base = [self.W[k] * mp.exp(t * self.u[k] ** 2) for k in range(self.N)]
            # fixed-point weights times u^j for j = 0..4 and antiderivative weights 1/u
            tab = {}
            for j in range(5):
                tab[j] = [self._fx(base[k] * self.u[k] ** j) for k in range(self.N)]
            tab['inv'] = [self._fx(base[k] / self.u[k]) if k > 0 else 0 for k in range(self.N)]
            tab['w0'] = base[0]
            if len(self._tcache) > 200:
                self._tcache.clear()
            self._tcache[key] = tab
        return self._tcache[key]

    def _phases(self, z):
        """fixed-point cos(z u_k), sin(z u_k) for all k by stable repeated multiplication;
        re-seeded exactly every 16 steps to keep error O(16 ulp)."""
        P = self.prec
        z = mp.mpf(z)
        C, S = [], []
        cs = self._fx(mp.cos(z * self.h)); sn = self._fx(mp.sin(z * self.h))
        c, s = self.one, 0
        for k in range(self.N):
            if k % 16 == 0 and k > 0:
                c = self._fx(mp.cos(z * self.u[k])); s = self._fx(mp.sin(z * self.u[k]))
            C.append(c); S.append(s)
            c, s = (c * cs - s * sn) >> P, (s * cs + c * sn) >> P
        return C, S

    def derivs(self, z, t, jmax=3):
        """[H, H', ..., H^(jmax)] (z-derivatives) at (z, t), as mpf."""
        tab = self._weights(t)
        C, S = self._phases(z)
        out = []
        for j in range(jmax + 1):
            w = tab[j]
            if j % 4 == 0:
                acc = sum(w[k] * C[k] for k in range(self.N))
            elif j % 4 == 1:
                acc = -sum(w[k] * S[k] for k in range(self.N))
            elif j % 4 == 2:
                acc = -sum(w[k] * C[k] for k in range(self.N))
            else:
                acc = sum(w[k] * S[k] for k in range(self.N))
            out.append(mp.ldexp(mp.mpf(acc), -2 * self.prec))
        return out

    def H(self, z, t):
        return self.derivs(z, t, 0)[0]

    def F(self, z, t):
        """antiderivative int_0^z H_t(x) dx"""
        tab = self._weights(t)
        C, S = self._phases(z)
        w = tab['inv']
        acc = sum(w[k] * S[k] for k in range(1, self.N))
        return tab['w0'] * mp.mpf(z) + mp.ldexp(mp.mpf(acc), -2 * self.prec)

    def dt(self, z, t):
        """d/dt H_t(z) computed directly (= sum W E u^2 cos) -- equals -H''"""
        tab = self._weights(t)
        C, S = self._phases(z)
        acc = sum(tab[2][k] * C[k] for k in range(self.N))
        return mp.ldexp(mp.mpf(acc), -2 * self.prec)


def xi(s):
    return s * (s - 1) / 2 * mp.pi ** (-s / 2) * mp.gamma(s / 2) * mp.zeta(s)
