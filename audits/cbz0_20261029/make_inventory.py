#!/usr/bin/env python3
"""Render cbz/INVENTORY.md from branches.tsv, prs.json and gate results (Phase 1)."""
import collections
import json
import sys

S = sys.argv[1]
rows = [l.rstrip('\n').split('\t') for l in open(S + '/branches.tsv')]
prs = json.load(open(S + '/prs.json'))
gates = json.load(open(S + '/gates.json'))
heads = json.load(open(S + '/heads.json'))

by = collections.defaultdict(lambda: collections.Counter())
age = collections.defaultdict(lambda: collections.Counter())
for repo, br, st, sha, date in rows:
    by[repo][st] += 1
    if st == 'unmerged':
        age[repo][date[:7]] += 1

out = []
w = out.append
w('# CBZ-0 Phase 1 inventory')
w('')
w('Generated by `audits/cbz0_20261029/make_inventory.py` from live remote state at %s. Regenerate it; do not hand-edit.' % gates['observed_at'])
w('Every count below is observed, not estimated. Status words follow STATUS truthfulness (Layer A7).')
w('')
w('## 1. Repositories and default heads')
w('')
w('| Repository | Default head | Remote branches | Merged into default | Unmerged | Unmerged by last-commit month | Open PRs |')
w('|---|---|---|---|---|---|---|')
prc = collections.Counter(p['repo'] for p in prs)
for repo in sorted(by):
    c = by[repo]
    months = ', '.join('%s: %d' % kv for kv in sorted(age[repo].items()))
    w('| `%s` | `%s` | %d | %d | %d | %s | %d |' % (repo, heads[repo], c['merged'] + c['unmerged'],
                                                   c['merged'], c['unmerged'], months or '—', prc.get(repo, 0)))
total = sum(sum(c.values()) for c in by.values())
w('')
w('Total remote branches: %d; merged into their default branch: %d; with unmerged commits: %d. '
  '"Unmerged" is by commit ancestry, so squash-merged branches also count as unmerged; it is an upper bound on live work.'
  % (total, sum(c['merged'] for c in by.values()), sum(c['unmerged'] for c in by.values())))
w('`trial` is archived on GitHub (read-only), so none of its refs can be changed from here.')
w('')
w('Per-branch rows (repo, branch, merged/unmerged, head, last commit date) are in `audits/cbz0_20261029/branches.tsv`.')
w('')
w('## 2. Open pull requests (%d)' % len(prs))
w('')
w('| Repository | # | Draft | Created | Last update | Title |')
w('|---|---|---|---|---|---|')
for p in sorted(prs, key=lambda p: (p['repo'], -p['number'])):
    w('| `%s` | %d | %s | %s | %s | %s |' % (p['repo'], p['number'], 'yes' if p['draft'] else 'no',
                                          p['created_at'][:10], p['updated_at'][:10], p['title'].replace('|', '\\|')))
w('')
w('## 3. Gate status observed now')
w('')
w('| Gate | Status | Evidence |')
w('|---|---|---|')
for g in gates['gates']:
    w('| %s | %s | %s |' % (g['gate'], g['status'], g['evidence']))
w('')
w('## 4. Tooling gaps (Phase 1 discovery)')
w('')
for t in gates['tooling_gaps']:
    w('- **%s** — %s' % (t['gap'], t['disposition']))
w('')
open(S + '/INVENTORY.md', 'w').write('\n'.join(out) + '\n')
print('wrote', len(out), 'lines')
