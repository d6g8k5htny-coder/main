"""Lexical extraction of Lean 4 declaration headers, for cross-repository drift checks.

Domain (B-006). This module sees declarations written literally in source:
`theorem`, `lemma`, `def`, `abbrev`, `instance` (named), `axiom`, `opaque`, `structure`,
`class` and `inductive`, with their modifiers, inside `namespace` / `section` blocks. It
does not elaborate, expand macros or notation, or see declarations generated by
commands such as `deriving`, `mutual` auto-names or user syntax. A header is the token
sequence from the keyword to the first top-level `:=`, `where` or line-leading `|`
(for `structure`, `class` and `inductive`, the whole body up to the next command), with
comments removed and whitespace normalized. The compared `interface` is the header for
`theorem`, `lemma`, `axiom` and `opaque` (proofs are irrelevant; opaque values are
hidden), and header plus value for every definition-like declaration, whose value is part
of its meaning. Equal interfaces mean equal source text, not equal elaborated terms;
unequal interfaces mean the source differs.

Fails closed: an unterminated comment, string or quoted name, an unbalanced `end`, or a
declaration keyword with no name raises LeanSyntaxError.
"""
from __future__ import annotations

import re

DECL_KEYWORDS = frozenset({
    'theorem', 'lemma', 'def', 'abbrev', 'instance', 'axiom', 'opaque',
    'structure', 'class', 'inductive', 'example',
})
BODY_KEYWORDS = frozenset({'structure', 'class', 'inductive'})
# proofs are irrelevant to meaning; opaque values are hidden by design
STATEMENT_ONLY = frozenset({'theorem', 'lemma', 'axiom', 'opaque', 'example'})
MODIFIERS = frozenset({'private', 'protected', 'noncomputable', 'unsafe', 'partial', 'nonrec'})
COMMANDS = DECL_KEYWORDS | MODIFIERS | frozenset({
    'namespace', 'section', 'end', 'open', 'variable', 'universe', 'set_option',
    'attribute', 'import', 'mutual', 'macro', 'macro_rules', 'syntax', 'notation',
    'infix', 'infixl', 'infixr', 'prefix', 'postfix', 'elab', 'elab_rules',
    'declare_syntax_cat', 'initialize', 'builtin_initialize', 'export', 'local', 'scoped',
    'omit', 'include', 'deriving',
})
OPEN = {'(': ')', '[': ']', '{': '}', '⟨': '⟩', '⦃': '⦄', '⟪': '⟫'}
CLOSE = {v: k for k, v in OPEN.items()}
RAW_OPEN = re.compile(r'r(#*)"')


class LeanSyntaxError(ValueError):
    pass


def _ident_start(c):
    return c.isalpha() or c == '_'


def _ident_char(c):
    return c.isalnum() or c in "_'!?"


def tokens(text):
    """Yield (kind, text, line, first_on_line). Kinds: ident, str, char, num, sym."""
    i, n, line, fresh = 0, len(text), 1, True
    while i < n:
        c = text[i]
        if c == '\n':
            line, fresh, i = line + 1, True, i + 1
            continue
        if c in ' \t\r':
            i += 1
            continue
        start_line, first = line, fresh
        fresh = False
        if text.startswith('--', i):
            j = text.find('\n', i)
            i = n if j < 0 else j
            fresh = first
            continue
        if text.startswith('/-', i):
            depth, i = 1, i + 2
            while depth:
                if i >= n:
                    raise LeanSyntaxError('unterminated comment opened on line %d' % start_line)
                if text.startswith('/-', i):
                    depth, i = depth + 1, i + 2
                elif text.startswith('-/', i):
                    depth, i = depth - 1, i + 2
                else:
                    line += text[i] == '\n'
                    i += 1
            fresh = first
            continue
        m = RAW_OPEN.match(text, i) if c == 'r' else None
        if m and (i == 0 or not _ident_char(text[i - 1])):
            close = '"' + m.group(1)
            j = text.find(close, m.end())
            if j < 0:
                raise LeanSyntaxError('unterminated raw string on line %d' % start_line)
            line += text.count('\n', i, j)
            yield 'str', text[i:j + len(close)], start_line, first
            i = j + len(close)
            continue
        if c == '"':
            j = i + 1
            while True:
                if j >= n:
                    raise LeanSyntaxError('unterminated string on line %d' % start_line)
                if text[j] == '\\':
                    j += 2
                elif text[j] == '"':
                    break
                else:
                    j += 1
            line += text.count('\n', i, j)
            yield 'str', text[i:j + 1], start_line, first
            i = j + 1
            continue
        if c == "'" and i + 2 < n and (text[i + 2] == "'" or (text[i + 1] == '\\' and "'" in text[i + 3:i + 12])):
            j = text.index("'", i + 2 if text[i + 1] != '\\' else i + 3)
            yield 'char', text[i:j + 1], start_line, first
            i = j + 1
            continue
        if c == '«' or _ident_start(c):
            j, parts = i, []
            while True:
                if j < n and text[j] == '«':
                    k = text.find('»', j)
                    if k < 0:
                        raise LeanSyntaxError('unterminated «name» on line %d' % start_line)
                    parts.append(text[j:k + 1])
                    j = k + 1
                elif j < n and _ident_start(text[j]):
                    k = j
                    while k < n and _ident_char(text[k]):
                        k += 1
                    parts.append(text[j:k])
                    j = k
                else:
                    break
                if j + 1 < n and text[j] == '.' and (text[j + 1] == '«' or _ident_start(text[j + 1])):
                    j += 1
                else:
                    break
            yield 'ident', '.'.join(parts), start_line, first
            i = j
            continue
        if c.isdigit():
            j = i
            while j < n and (text[j].isalnum() or text[j] in '._'):
                j += 1
            yield 'num', text[i:j], start_line, first
            i = j
            continue
        if text.startswith(':=', i):
            yield 'sym', ':=', start_line, first
            i += 2
            continue
        yield 'sym', c, start_line, first
        i += 1


def declarations(text, unit=''):
    """Return a list of dicts: name, kind, header, line, private, modifiers.

    `unit` disambiguates `private` names, which are file-local and never compared.
    """
    toks = list(tokens(text))
    out, scopes, i, n = [], [], 0, len(toks)

    def current_ns():
        return [p for kind, parts in scopes if kind == 'namespace' for p in parts]

    while i < n:
        kind, tx, line, first = toks[i]
        if kind == 'ident' and tx in ('namespace', 'section'):
            name = toks[i + 1][1] if i + 1 < n and toks[i + 1][0] == 'ident' and toks[i + 1][2] == line else ''
            if tx == 'namespace' and not name:
                raise LeanSyntaxError('namespace without a name on line %d' % line)
            scopes.append((tx, name.split('.') if name else []))
            i += 2 if name else 1
            continue
        if kind == 'ident' and tx == 'end':
            name = toks[i + 1][1] if i + 1 < n and toks[i + 1][0] == 'ident' and toks[i + 1][2] == line and toks[i + 1][1] not in COMMANDS else ''
            parts = name.split('.') if name else []
            if not scopes:
                raise LeanSyntaxError('unbalanced end on line %d' % line)
            skind, sparts = scopes[-1]
            if sparts != parts:
                raise LeanSyntaxError('end %s on line %d closes %s %s' % (name or '(anonymous)', line, skind, '.'.join(sparts) or '(anonymous)'))
            scopes.pop()
            i += 2 if name else 1
            continue
        if kind == 'ident' and (tx in DECL_KEYWORDS or tx in MODIFIERS):
            # collect modifiers, attributes already passed as symbols
            mods, j = [], i
            while j < n and toks[j][0] == 'ident' and toks[j][1] in MODIFIERS:
                mods.append(toks[j][1])
                j += 1
            if j >= n or toks[j][0] != 'ident' or toks[j][1] not in DECL_KEYWORDS:
                i = max(j, i + 1)
                continue
            dkind, dline = toks[j][1], toks[j][2]
            j += 1
            if dkind == 'instance' and j < n and toks[j][1] == '(':
                depth = 0
                while j < n:
                    depth += toks[j][1] == '('
                    depth -= toks[j][1] == ')'
                    j += 1
                    if depth == 0:
                        break
            name = None
            if dkind != 'example' and j < n and toks[j][0] == 'ident' and toks[j][1] not in COMMANDS and toks[j][1] != 'where':
                name = toks[j][1]
                j += 1
            if name is None and dkind not in ('example', 'instance'):
                raise LeanSyntaxError('%s without a name on line %d' % (dkind, dline))
            hdr, depth = [], 0
            while j < n:
                k, t, ln, fst = toks[j]
                if depth == 0:
                    if k == 'ident' and t in COMMANDS and not (t == 'deriving' and dkind in BODY_KEYWORDS):
                        break
                    if k == 'sym' and t == '@' and j + 1 < n and toks[j + 1][1] == '[':
                        break
                    if k == 'sym' and t == '#' and fst and j + 1 < n and toks[j + 1][0] == 'ident':
                        break
                    if dkind not in BODY_KEYWORDS:
                        if (k == 'sym' and t == ':=') or (k == 'ident' and t == 'where') or (k == 'sym' and t == '|' and fst):
                            break
                if k == 'sym' and t in OPEN:
                    depth += 1
                elif k == 'sym' and t in CLOSE:
                    depth = max(depth - 1, 0)
                hdr.append(t)
                j += 1
            # the rest of the declaration, up to the next top-level command
            body = []
            while j < n:
                k, t, ln, fst = toks[j]
                if depth == 0 and (
                        (k == 'ident' and t in COMMANDS and t != 'deriving')
                        or (k == 'sym' and t == '@' and j + 1 < n and toks[j + 1][1] == '[')
                        or (k == 'sym' and t == '#' and fst and j + 1 < n and toks[j + 1][0] == 'ident')):
                    break
                if k == 'sym' and t in OPEN:
                    depth += 1
                elif k == 'sym' and t in CLOSE:
                    depth = max(depth - 1, 0)
                body.append(t)
                j += 1
            if name is not None:
                full = name[len('_root_.'):] if name.startswith('_root_.') else '.'.join(current_ns() + [name])
                header = ' '.join(hdr)
                out.append({
                    'name': full, 'kind': dkind, 'header': header, 'line': dline,
                    'private': 'private' in mods, 'unit': unit,
                    'modifiers': sorted(m for m in mods if m != 'private'),
                    # what must agree across copies: the statement of a proposition, the
                    # statement and value of a definition (its value is part of its meaning)
                    'interface': header if dkind in STATEMENT_ONLY else ' '.join(hdr + body),
                })
            i = j
            continue
        i += 1
    return out
