    def quiesce(self):
        self.quiesced = True  # One disposal attempt; failures are retained, never retried.
        started_at, start = datetime.datetime.now(datetime.timezone.utc).isoformat(), time.monotonic_ns()
        deadline = time.monotonic() + 90
        self.recovery_custody = True  # Reserved bytes/count are for bounded recovery evidence.
        def refuse(name, code):
            self.safe_to_collect, self.exit_status = False, 1
            self.collection_refused.append({"path": name, "reason_code": code})
        for record in self.containers:
            if record["remaining"] == []:
                continue
            stopped = removed = query = None
            if time.monotonic() < deadline:
                stopped = actual_run(["docker", "stop", "--time", "10", record["name"]],
                                     min(20, max(0.1, deadline - time.monotonic())), cap=65536)
            if time.monotonic() < deadline:
                removed = actual_run(["docker", "rm", record["name"]],
                                     min(15, max(0.1, deadline - time.monotonic())), cap=65536)
            if time.monotonic() < deadline:
                query = actual_run(["docker", "ps", "-a", "--filter", "name=^/" + record["name"] + "$",
                                    "--format", "{{.Names}}"], min(10, max(0.1, deadline - time.monotonic())), cap=65536)
            record["stop_status"], record["remove_status"] = stopped["status"] if stopped else None, removed["status"] if removed else None
            record["absence_query_status"] = query["status"] if query else None
            try:
                record["remaining"] = query["raw"].decode("ascii").splitlines() if query and query["status"] == 0 and query["raw"] is not None else None
            except Exception:
                record["remaining"] = None
            try:
                self.json("status/" + record["stage"].lower() + "-exception-disposal.json", {
                    **META, "stop_status": record["stop_status"], "remove_status": record["remove_status"],
                    "absence_query_status": record["absence_query_status"], "remaining": record["remaining"]})
            except Exception:
                refuse("status/" + record["stage"].lower(), "DISPOSAL_CUSTODY_UNCONFIRMED")
            if record["remaining"] != [] or record["stop_status"] != 0 or record["remove_status"] != 0:
                refuse("status/" + record["stage"].lower(), "WRITER_ABSENCE_UNCONFIRMED")
        processes = [*({"stage": "native-" + str(item["ticket"]).zfill(3), "name": "native-command",
                        "process": item["process"]} for item in self.native_processes), *self.attach_processes]
        for item in processes:
            process, terminated, killed, reaped, codes = item["process"], False, False, False, []
            if time.monotonic() < deadline:
                try:
                    if process.poll() is None:
                        try:
                            process.terminate()
                            terminated = True
                        except Exception:
                            codes.append("TERM_EXCEPTION")
                    try:
                        process.wait(timeout=min(5, max(0.1, deadline - time.monotonic())))
                        reaped = True
                    except Exception:
                        try:
                            process.kill()
                            killed = True
                        except Exception:
                            codes.append("KILL_EXCEPTION")
                        try:
                            process.wait(timeout=min(5, max(0.1, deadline - time.monotonic())))
                            reaped = True
                        except Exception:
                            codes.append("REAP_UNCONFIRMED")
                except Exception:
                    codes.append("PROCESS_OBSERVATION_EXCEPTION")
            else:
                codes.append("RECOVERY_TOTAL_CAP")
            try:
                self.json("status/" + item["stage"].lower() + "-attach-reap.json", {
                    **META, "name": item["name"], "pid": process.pid, "exit_status": process.returncode,
                    "terminated": terminated, "killed": killed, "reaped": reaped, "error_codes": sorted(set(codes))})
            except Exception:
                refuse("status/" + item["stage"].lower(), "REAP_CUSTODY_UNCONFIRMED")
            if not reaped:
                refuse("status/" + item["stage"].lower(), "ATTACH_REAP_UNCONFIRMED")
        for record in self.volumes:
            try:
                observed, record["mount_after"] = self.observe_mount(record, "recovery")
                if observed["presence"] == "UNKNOWN":
                    refuse("status/mount-" + record["stage"], "MOUNT_PRESENCE_UNKNOWN")
            except Exception:
                refuse("status/mount-" + record["stage"], "MOUNT_OBSERVATION_UNCONFIRMED")
        self.recovery_custody = False
        if self.containers:
            self.phase_timings.append({"phase": "DISPOSE", "started_at": started_at,
                                       "ended_at": datetime.datetime.now(datetime.timezone.utc).isoformat(),
                                       "start_ns": start, "end_ns": time.monotonic_ns()})
        if time.monotonic() > deadline:
            refuse("status/disposal", "DISPOSAL_TOTAL_CAP")

