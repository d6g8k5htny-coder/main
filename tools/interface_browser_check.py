    def command_audit(self, phase, argv, result):
        # Constructor-owned native execution evidence. Public inputs/candidate
        # code cannot choose the sink, command, timing or status. Never record
        # environments, HTTP credentials or signed artifact redirect URLs.
        require(all(type(item) is str and len(item.encode()) <= 8192 for item in argv))
        if phase == "BEGIN":
            require(self.command_count < 256, "NATIVE_COMMAND_COUNT")
            ticket = self.command_count
            self.command_count += 1
            self.command_records[ticket] = {"argv": list(argv), "started_ns": time.monotonic_ns(),
                                            "pid": None, "end": None}
            self.json("status/command-" + str(ticket).zfill(3) + "-begin.json",
                      {**META, "argv": argv, "started_ns": self.command_records[ticket]["started_ns"]})
            return ticket
        ticket = result["ticket"]
        if ticket is None:
            candidates = [key for key, row in self.command_records.items()
                          if row["argv"] == argv and row["end"] is None]
            if not candidates:
                self.collection_refused.append({"path": "status/command-attempt", "reason_code": "BEGIN_NOT_ENROLLED"})
                return None
            ticket = max(candidates)
        integer(ticket, 0, 255)
        if phase == "SPAWN":
            self.native_processes.append({"ticket": ticket, "process": result["process"]})
            self.command_records[ticket]["pid"] = result["process"].pid
            return ticket
        require(phase == "END")
        prefix = result["prefix"]
        require(type(prefix) is bytes and len(prefix) <= 4 * 2**20)
        end = {key: value for key, value in result.items() if key not in ("raw", "prefix", "ticket")}
        self.command_records[ticket]["end"] = end  # Enroll before a durable copy can fail.
        require(sum(map(len, self.command_prefixes.values())) + len(prefix) <= 8 * 2**20,
                "UNADMITTED_PREFIX_MEMORY_BOUND")
        self.command_prefixes[ticket] = prefix
        original = self.retain("logs/command-" + str(ticket).zfill(3) + ".log", prefix)
        self.json("status/command-" + str(ticket).zfill(3) + "-end.json", {
            **META, "argv": argv, **end, "stream": original,
            "complete_stream": result["raw"] is not None,
            "scope": "complete observed stream" if result["raw"] is not None else "explicit incomplete prefix; refused"})
        self.command_prefixes.pop(ticket, None)
        return ticket

    def retain(self, name, raw):
        safe(name)
        require(type(raw) is bytes and len(raw) <= 128 * 2**20 and
                name not in self.allowed and name not in self.pending_originals, "RETAIN_ENROLLMENT")
        if self.canary is not None and self.canary in raw:
            self.collection_refused.append({"path": name, "reason_code": "TEST_CANARY_REFUSED"})
            raise Refused("TEST_CANARY_REFUSED")
        limit, count = (256 * 2**20, 1024) if self.recovery_custody else (240 * 2**20, 960)
        require(len(self.allowed) + len(self.pending_originals) + 1 <= count and
                sum(row["bytes"] for row in self.allowed.values()) +
                sum(row["bytes"] for row in self.pending_originals.values()) + len(raw) <= limit, "PUBLICATION_RESERVATION")
        row = desc(name, raw)
        self.pending_originals[name] = row  # Before physical mutation.
        new_file(self.publish, name, raw)
        require(read_at(self.publish, name, max(1, len(raw))) == raw, "RETAIN_BYTE_JOIN")
        self.allowed[name], self.safe_originals[name] = row, raw
        self.pending_originals.pop(name)
        return row

