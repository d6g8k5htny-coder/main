def preparation_commands(members):
    """Lossless native START/END JSONL, bounded, unique, complete on success."""
    require("native/command-originals.jsonl" in members, "PREPARATION_NATIVE_COMMAND_ORIGINAL")
    raw = members["native/command-originals.jsonl"]
    require(0 < len(raw) <= 4 * 2**20 and raw.endswith(b"\n"), "PREPARATION_NATIVE_COMMAND_BOUND")
    starts, ends = {}, {}
    for line in raw.splitlines():
        row = strict(line)
        require(type(row) is dict and row.get("event") in ("START", "END"))
        ticket = row["ticket"]
        require(type(ticket) is str and re.fullmatch(r"native/commands/[0-9]{4}-[a-z0-9-]+", ticket),
                "PREPARATION_NATIVE_COMMAND_TICKET")
        if row["event"] == "START":
            closed(row, ("event", "ticket", "argv", "seconds", "stream_cap", "started_at"))
            require(ticket not in starts and ticket not in ends and len(starts) < 2048)
            require(type(row["argv"]) is list and 0 < len(row["argv"]) <= 2048 and all(
                type(a) is str and 0 < len(a.encode()) <= 8192 and "\x00" not in a for a in row["argv"]))
            require(type(row["seconds"]) in (int, float) and 0 < row["seconds"] <= 420
                    and row["stream_cap"] == 4194304 and type(row["stream_cap"]) is int)
            require(type(row["started_at"]) is str and re.fullmatch(
                r"[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}(?:\.[0-9]+)?(?:Z|\+00:00)", row["started_at"]))
            starts[ticket] = row
        else:
            closed(row, ("event", "ticket", "exit_status", "duration_ns", "timed_out", "overflow",
                         "term_status", "kill_status", "reaped", "stdout", "stderr",
                         "stdout_base64", "stderr_base64", "stdout_bytes", "stdout_sha256",
                         "stderr_bytes", "stderr_sha256"))
            require(ticket in starts and ticket not in ends, "PREPARATION_NATIVE_COMMAND_JOIN")
            require(type(row["exit_status"]) is int and row["exit_status"] == 0
                    and type(row["timed_out"]) is bool and row["timed_out"] is False
                    and type(row["overflow"]) is bool and row["overflow"] is False
                    and row["reaped"] is True and type(row["reaped"]) is bool
                    and row["term_status"] is None and row["kill_status"] is None,
                    "PREPARATION_NATIVE_COMMAND_COMPLETE_SUCCESS")
            integer(row["duration_ns"], 1)
            total = 0
            for stream in ("stdout", "stderr"):
                require(row[stream] == "native/command-originals.jsonl"
                        and type(row[stream + "_base64"]) is str)
                try:
                    decoded = base64.b64decode(row[stream + "_base64"], validate=True)
                except (ValueError, binascii.Error):
                    raise Refused("PREPARATION_NATIVE_COMMAND_BASE64") from None
                integer(row[stream + "_bytes"], 0, 4194304)
                require(type(row[stream + "_sha256"]) is str and HEX.fullmatch(row[stream + "_sha256"])
                        and len(decoded) == row[stream + "_bytes"] and sha(decoded) == row[stream + "_sha256"],
                        "PREPARATION_NATIVE_COMMAND_STREAM_JOIN")
                total += len(decoded)
            require(total <= starts[ticket]["stream_cap"], "PREPARATION_NATIVE_COMMAND_STREAM_CAP")
            ends[ticket] = row
    require(starts and set(starts) == set(ends), "PREPARATION_NATIVE_COMMAND_COMPLETE_PAIRS")
    argv = [row["argv"] for row in starts.values()]
    for image in (BUILD_IMAGE, BROWSER_IMAGE):
        pulls = [a for a in argv if a in (["docker", "pull", image], ["docker", "image", "pull", image])]
        require(len(pulls) == 1, "PREPARATION_NATIVE_SINGLE_ACQUISITION")
    creates = [a for a in argv if a[:2] == ["docker", "create"] or a[:3] == ["docker", "container", "create"]]
    require(len(creates) >= 3 and all("--pull=never" in a for a in creates),
            "PREPARATION_NATIVE_PULL_NEVER")
    return starts, ends


def preparation_include_closure(policy, rows, members):
    """Fixed policy references only; reject unresolved or unused include records."""
    require(type(rows) is list and 0 < len(rows) <= 64, "PREPARATION_INCLUDE_COUNT")
    by_name = {}
    for row in rows:
        raw = prep_record(row, members, 2**20)
        require(row["path"].startswith("native/apparmor-includes/"), "PREPARATION_INCLUDE_ROOT")
        name = row["path"][len("native/apparmor-includes/"):]
        safe(name)
        require(name not in by_name)
        by_name[name] = (row, raw)
    referenced, pending = set(), [policy]
    pattern = re.compile(r"^\s*(?:#\s*)?(?:include|abi)\s+<([^>]+)>\s*,?\s*(?:#.*)?$", re.MULTILINE)
    while pending:
        text = pending.pop().decode("utf-8", "strict")
        for match in pattern.finditer(text):
            name = safe(match.group(1))
            require(name in by_name, "PREPARATION_UNRESOLVED_POLICY_INCLUDE")
            if name not in referenced:
                referenced.add(name)
                pending.append(by_name[name][1])
    require("abi/4.0" in referenced and referenced == set(by_name), "PREPARATION_COMPLETE_POLICY_INCLUDE_JOIN")
    return [by_name[name][0] for name in sorted(by_name)]


