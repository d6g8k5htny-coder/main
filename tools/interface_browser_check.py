def strict(raw):
    require(type(raw) is bytes and len(raw) <= 4 * 2**20 and not raw.startswith(b"\xef\xbb\xbf"))
    def pairs(items):
        result = {}
        for key, item in items:
            require(key not in result, "DUPLICATE_JSON_KEY")
            result[key] = item
        return result
    try:
        value = json.loads(raw.decode("utf-8", "strict"), object_pairs_hook=pairs,
                           parse_constant=lambda _: (_ for _ in ()).throw(Refused("NONFINITE_JSON")))
    except (UnicodeError, ValueError, RecursionError):
        raise Refused("STRICT_JSON_REFUSED") from None
    def visit(item, depth=0):
        require(depth <= 64, "JSON_DEPTH")
        if isinstance(item, str):
            require(not any(0xD800 <= ord(c) <= 0xDFFF for c in item), "SURROGATE_JSON")
        elif isinstance(item, list):
            for child in item:
                visit(child, depth + 1)
        elif isinstance(item, dict):
            for key, child in item.items():
                visit(key, depth + 1)
                visit(child, depth + 1)
        elif isinstance(item, float):
            require(item == item and abs(item) != float("inf"), "NONFINITE_JSON")
    visit(value)
    return value


