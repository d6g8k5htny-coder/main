NATIVE_COMMAND_SINK = None  # Trusted host construction only, never candidate input.

def actual_run(argv, seconds, cap=4 * 2**20, env=None, cwd=None):
    """One command; retain bounded prefixes and terminal/reap uncertainty on every exit."""
    require(type(argv) is list and argv and all(type(a) is str for a in argv))
    require(type(seconds) in (int, float) and 0 < seconds <= 900)
    integer(cap, 1, 4 * 2**20)
    started, sink = time.monotonic_ns(), NATIVE_COMMAND_SINK
    ticket, process, selector = None, None, None
    raw, observed_bytes, errors = bytearray(), 0, []
    timed_out = overflow = eof = reaped = spawn_attempted = False
    term_status = kill_status = None
    def retain_part(part):
        nonlocal observed_bytes, overflow
        observed_bytes += len(part)
        raw.extend(part[:max(0, cap - len(raw))])
        overflow = observed_bytes > cap
    try:
        if sink is not None:
            ticket = sink("BEGIN", argv, None)
        spawn_attempted = True
        process = subprocess.Popen(argv, stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
                                   stderr=subprocess.STDOUT, env=env, cwd=cwd, start_new_session=True)
        if sink is not None:
            sink("SPAWN", argv, {"ticket": ticket, "process": process})
        import selectors
        selector = selectors.DefaultSelector()
        os.set_blocking(process.stdout.fileno(), False)
        selector.register(process.stdout, selectors.EVENT_READ)
        deadline = time.monotonic() + seconds
        while selector.get_map():
            if time.monotonic() >= deadline or overflow:
                timed_out = time.monotonic() >= deadline
                break
            for key, _ in selector.select(min(0.2, max(0, deadline - time.monotonic()))):
                try:
                    part = os.read(key.fd, 65536)
                except BlockingIOError:
                    continue
                if not part:
                    eof = True
                    selector.unregister(key.fileobj)
                else:
                    retain_part(part)
        if not timed_out and not overflow:
            try:
                process.wait(timeout=max(0.001, deadline - time.monotonic()))
                reaped = True
            except subprocess.TimeoutExpired:
                timed_out = True
                errors.append("FINAL_WAIT_TIMEOUT")
    except BaseException:
        errors.append("SPAWN_OR_STREAM_OBSERVATION_EXCEPTION")
    finally:
        if selector is not None:
            try:
                selector.close()
            except Exception:
                errors.append("SELECTOR_CLOSE_EXCEPTION")
        if process is not None and not reaped:
            try:
                if process.poll() is None:
                    process.terminate()
                    term_status = 0
            except Exception:
                term_status = 1
                errors.append("TERM_EXCEPTION")
            try:
                process.wait(timeout=10)
                reaped = True
            except Exception:
                try:
                    process.kill()
                    kill_status = 0
                except Exception:
                    kill_status = 1
                    errors.append("KILL_EXCEPTION")
                try:
                    process.wait(timeout=10)
                    reaped = True
                except Exception:
                    errors.append("POST_KILL_REAP_UNCONFIRMED")
            if process.stdout is not None:
                try:
                    os.set_blocking(process.stdout.fileno(), False)
                    drain_deadline = time.monotonic() + 1
                    while not overflow and time.monotonic() < drain_deadline:
                        try:
                            part = os.read(process.stdout.fileno(), 65536)
                        except BlockingIOError:
                            break
                        if not part:
                            eof = True
                            break
                        retain_part(part)
                except Exception:
                    errors.append("RECOVERY_STREAM_EXCEPTION")
        if process is not None and process.stdout is not None:
            try:
                process.stdout.close()
            except Exception:
                errors.append("STREAM_CLOSE_EXCEPTION")
        complete = process is not None and reaped and eof and not timed_out and not overflow and not errors
        result = {"status": process.returncode if process is not None and reaped else None,
                  "duration_ns": time.monotonic_ns() - started, "timeout": timed_out, "overflow": overflow,
                  "raw": bytes(raw) if complete else None, "prefix": bytes(raw), "observed_bytes": observed_bytes,
                  "spawn_attempted": spawn_attempted, "pid": process.pid if process is not None else None,
                  "reaped": reaped, "term_status": term_status, "kill_status": kill_status,
                  "stream_eof": eof, "error_codes": sorted(set(errors))}
        if sink is not None:
            try:
                sink("END", argv, {"ticket": ticket, **result})
            except Exception:
                result["raw"] = None
                result["error_codes"] = sorted(set([*result["error_codes"], "END_CUSTODY_EXCEPTION"]))
        return result


