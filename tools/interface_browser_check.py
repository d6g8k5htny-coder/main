class ArtifactServer(http.server.ThreadingHTTPServer):
    daemon_threads = True
    def __init__(self, root, rows):
        self.root = root
        self.allowed = {row["path"]: row for row in rows}
        super().__init__(("127.0.0.1", 8765), ArtifactHandler)


class ArtifactHandler(http.server.BaseHTTPRequestHandler):
    def log_message(self, *_):
        pass

    def do_GET(self):
        parsed = urllib.parse.urlsplit(self.path)
        if parsed.scheme or parsed.netloc or parsed.query or parsed.fragment or not parsed.path.startswith(BASE):
            self.send_error(404)
            return
        # Routes preserve a single encodeURIComponent segment; reject separators,
        # dot aliases and double encoding rather than translating a caller root.
        rel = parsed.path[len(BASE):]
        if not rel:
            rel = "index.html"
        elif rel.endswith("/"):
            rel += "index.html"
        if rel not in self.server.allowed:
            self.send_error(404)
            return
        row = self.server.allowed[rel]
        try:
            raw = read_at(self.server.root, rel, 2 * 2**20)
            require(desc(rel, raw) == row, "SERVED_TREE_CHANGED")
        except Refused:
            self.send_error(500)
            return
        kind = ("text/html; charset=utf-8" if rel.endswith(".html") else
                "text/javascript; charset=utf-8" if rel.endswith(".mjs") else
                "text/css; charset=utf-8" if rel.endswith(".css") else
                "application/json; charset=utf-8" if rel.endswith(".json") else
                "image/svg+xml" if rel.endswith(".svg") else "text/plain; charset=utf-8")
        self.send_response(200)
        self.send_header("Content-Type", kind)
        self.send_header("Content-Length", str(len(raw)))
        self.send_header("Content-Security-Policy", CSP)
        self.send_header("X-Content-Type-Options", "nosniff")
        self.end_headers()
        self.wfile.write(raw)


