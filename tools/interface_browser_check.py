    def validate_container(self, obj, image, executable, argv, mounts, browser, environment, image_config, running):
        require(obj["Config"]["Image"] == image and obj["Image"] ==
                (self.browser_runtime["image_id"] if browser else self.build_runtime["image_id"]))
        require(obj["Config"]["Entrypoint"] == [executable] and obj["Config"]["Cmd"] == argv,
                "EXACT_CONTAINER_ARGV")
        require(obj["Config"]["User"] == "65532:65532" and obj["Config"]["WorkingDir"] == "/")
        require((obj["Config"]["Labels"] or {}) == (image_config.get("Labels") or {}), "IMAGE_LABEL_BINDING")
        expected_env = dict(item.split("=", 1) for item in image_config.get("Env", []))
        expected_env.update(environment)
        observed_env = obj["Config"]["Env"]
        require(type(observed_env) is list and len({item.split("=", 1)[0] for item in observed_env}) == len(observed_env)
                and dict(item.split("=", 1) for item in observed_env) == expected_env, "CLOSED_ENVIRONMENT")
        h = obj["HostConfig"]
        require(h["NetworkMode"] == "none" and h["ReadonlyRootfs"] is True
                and h["CapDrop"] == ["ALL"] and h["Privileged"] is False
                and h["NanoCpus"] == 2_000_000_000 and h["Memory"] == 2 * 2**30
                and h["MemorySwap"] == 2 * 2**30 and h["PidsLimit"] == 256
                and h["IpcMode"] == "private" and h["CgroupnsMode"] == "private" and h["PidMode"] == ""
                and h["LogConfig"]["Type"] == "none" and not h["PortBindings"]
                and not h["Devices"] and not h["DeviceRequests"], "NATIVE_CONTROLS")
        require(sorted((r["Name"], r["Soft"], r["Hard"]) for r in h["Ulimits"]) ==
                [("fsize", 134217728, 134217728), ("nofile", 512, 512)])
        require(h["CapAdd"] in (None, []))
        require(h["Tmpfs"] == {"/tmp": "rw,noexec,nosuid,nodev,size=67108864,mode=1777"})
        native_security_options(h["SecurityOpt"],
                                read_at(self.runtime_root, self.sandbox["seccomp"], 2**20) if browser else None)
        if browser:
            require(obj["AppArmorProfile"] == self.sandbox["profile_id"])
        actual = sorted([{"source": m["Source"], "destination": m["Destination"], "readonly": m["RW"] is False}
                         for m in obj["Mounts"] if m["Type"] == "bind"], key=lambda m: m["destination"])
        expected = sorted(mounts, key=lambda m: m["destination"])
        require(actual == expected and all(m["Type"] in ("bind", "tmpfs") for m in obj["Mounts"]),
                "CLOSED_MOUNT_JOIN")
        tmpfs_mounts = [m for m in obj["Mounts"] if m["Type"] == "tmpfs"]
        require(len(tmpfs_mounts) <= 1 and all(m["Destination"] == "/tmp" and m["RW"] is True for m in tmpfs_mounts),
                "CLOSED_TMPFS_JOIN")
        require(obj["State"]["Running"] is running)

