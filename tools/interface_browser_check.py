def native_policy_settings():
    """Only this fixed public kernel-policy inventory; absent fields remain explicit."""
    paths = ("/sys/module/apparmor/parameters/enabled",
             "/proc/sys/kernel/apparmor_restrict_unprivileged_userns",
             "/proc/sys/kernel/unprivileged_userns_clone", "/proc/sys/user/max_user_namespaces")
    rows = []
    for path in paths:
        try:
            fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
        except FileNotFoundError:
            rows.append({"path": path, "presence": "ABSENT", "bytes": None, "sha256": None, "value": None})
            continue
        try:
            raw = bytearray()
            while len(raw) <= 65536:
                part = os.read(fd, 65537 - len(raw))
                if not part:
                    break
                raw.extend(part)
            require(len(raw) <= 65536, "POLICY_SETTINGS_BOUND")
            value = bytes(raw)
            rows.append({"path": path, "presence": "PRESENT", "bytes": len(value),
                         "sha256": sha(value), "value": value.decode("ascii", "strict")})
        finally:
            os.close(fd)
    return {**META, "files": rows}


