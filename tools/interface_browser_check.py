    def extract_google(self, ar_members, expected_chrome):
        # Fixed original data archive, never dpkg/install/script execution.
        # Bounded full decompression makes trailing bytes and tar coverage
        # independently observable; a streaming parser cannot discard its buffer.
        expanded = self.work / "google-data.tar"
        digest, expanded_bytes = hashlib.sha256(), 0
        fd = os.open(expanded, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
        try:
            with lzma.LZMAFile(io.BytesIO(ar_members["data.tar.xz"]), "rb") as compressed:
                while True:
                    part = compressed.read(65536)
                    if not part:
                        break
                    expanded_bytes += len(part)
                    require(expanded_bytes <= 512 * 2**20, "GOOGLE_DATA_TAR_EXPANDED_BOUND")
                    digest.update(part)
                    view = memoryview(part)
                    while view:
                        count = os.write(fd, view)
                        require(count > 0, "GOOGLE_EXPANDED_SHORT_WRITE")
                        view = view[count:]
            os.fsync(fd)
        finally:
            os.close(fd)
        rows, seen, actual, total = [], set(), set(), 0
        with expanded.open("rb") as stream:
            before = os.fstat(stream.fileno())
            require(stat.S_ISREG(before.st_mode) and before.st_nlink == 1
                    and before.st_size == expanded_bytes, "GOOGLE_EXPANDED_REGULAR")
            with tarfile.open(fileobj=stream, mode="r:") as archive:
                for entry in archive:
                    require(len(rows) < 512 and entry.name not in seen, "GOOGLE_TAR_COUNT_ALIAS")
                    seen.add(entry.name)
                    name = entry.name[2:] if entry.name.startswith("./") else entry.name
                    if name in ("", "."):
                        require(entry.isdir() and entry.size == 0, "GOOGLE_TAR_ROOT")
                    else:
                        safe(name.rstrip("/"))
                    require(entry.isfile() or entry.isdir() or entry.issym() or entry.islnk(), "GOOGLE_TAR_SPECIAL")
                    require(0 <= entry.size <= 512 * 2**20, "GOOGLE_TAR_MEMBER_SIZE")
                    total += entry.size
                    require(total <= 512 * 2**20, "GOOGLE_TAR_TOTAL")
                    raw = None
                    if entry.isfile():
                        source = archive.extractfile(entry)
                        require(source is not None)
                        raw = source.read(entry.size + 1)
                        require(len(raw) == entry.size, "GOOGLE_TAR_COMPLETE_MEMBER")
                    rows.append({"path": entry.name, "kind": "REGULAR" if entry.isfile() else "DIRECTORY" if entry.isdir() else
                                 "SYMLINK" if entry.issym() else "HARDLINK", "mode": entry.mode, "uid": entry.uid,
                                 "gid": entry.gid, "bytes": entry.size, "sha256": sha(raw) if raw is not None else None,
                                 "link_target": entry.linkname if entry.issym() or entry.islnk() else None})
                    if name.startswith("opt/google/chrome/"):
                        relative = name[len("opt/google/chrome/"):].rstrip("/")
                        if entry.isdir():
                            continue
                        require(entry.isfile() and relative in expected_chrome and relative not in actual,
                                "GOOGLE_PREFIX_REGULAR_ONLY")
                        actual.add(relative)
                        require(desc(relative, raw) == expected_chrome[relative], "GOOGLE_TREE_BYTE_JOIN")
                        new_file_large(self.chrome_root, relative, raw, 512 * 2**20)
                final_offset = archive.offset
            require(0 <= final_offset <= expanded_bytes, "GOOGLE_TAR_END_OFFSET")
            stream.seek(final_offset)
            trailing = 0
            while True:
                part = stream.read(65536)
                if not part:
                    break
                trailing += len(part)
                require(trailing <= 2 * 2**20 and not any(part), "GOOGLE_TAR_TRAILING_DATA")
            require(stable(before) == stable(os.fstat(stream.fileno())), "GOOGLE_EXPANDED_CHANGED")
        require(actual == set(expected_chrome) and len(rows) == 289, "GOOGLE_VENDOR_COMPLETE_INVENTORY")
        self.json("preparation/google-deb-tar-members.json", {**META, "members": rows,
                  "expanded_data_tar": {"bytes": expanded_bytes, "sha256": digest.hexdigest()},
                  "regular_total_bytes": total, "extracted_chrome_files": len(actual),
                  "extracted_chrome_bytes": sum(row["bytes"] for row in expected_chrome.values())})
        expanded.unlink()  # Complete observation retained; free bounded scratch.

