def read_at(root, name, cap=4 * 2**20):
    """Every ancestor opened no-follow; actual regular single-link member stable."""
    safe(name)
    flags = os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK
    fd = os.open(root, flags | os.O_DIRECTORY)
    try:
        parts = name.split("/")
        for part in parts[:-1]:
            next_fd = os.open(part, flags | os.O_DIRECTORY, dir_fd=fd)
            os.close(fd)
            fd = next_fd
        leaf = os.open(parts[-1], flags, dir_fd=fd)
        try:
            before = os.fstat(leaf)
            require(stat.S_ISREG(before.st_mode) and before.st_nlink == 1
                    and 0 <= before.st_size <= cap, "REGULAR_MEMBER_REFUSED")
            raw = bytearray()
            while len(raw) <= cap:
                chunk = os.read(leaf, min(65536, cap + 1 - len(raw)))
                if not chunk:
                    break
                raw.extend(chunk)
            after = os.fstat(leaf)
            require(stable(before) == stable(after) and len(raw) == before.st_size
                    and len(raw) <= cap, "CHANGING_MEMBER_REFUSED")
            return bytes(raw)
        finally:
            os.close(leaf)
    finally:
        os.close(fd)


