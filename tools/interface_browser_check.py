def inventory(root, file_cap=2 * 2**20, total_cap=32 * 2**20, count_cap=512, allow_source_maps=False):
    rows, folded = [], set()
    def walk(directory, prefix=""):
        for entry in sorted(os.scandir(directory), key=lambda item: item.name):
            name = prefix + entry.name
            safe(name)
            require(name.casefold() not in folded, "CASE_ALIAS")
            folded.add(name.casefold())
            st = entry.stat(follow_symlinks=False)
            if stat.S_ISDIR(st.st_mode):
                walk(entry.path, name + "/")
            else:
                require(stat.S_ISREG(st.st_mode) and st.st_nlink == 1, "NONREGULAR_OUTPUT")
                require(allow_source_maps or not name.endswith(".map"), "SOURCE_MAP_REFUSED")
                rows.append(desc(name, read_at(root, name, file_cap)))
                require(len(rows) <= count_cap and sum(r["bytes"] for r in rows) <= total_cap,
                        "TREE_CAP")
    walk(root)
    return sorted(rows, key=lambda row: row["path"])


def readonly_tree(root, executable=False):
    for directory, dirs, files in os.walk(root, followlinks=False):
        require(not pathlib.Path(directory).is_symlink(), "READONLY_ROOT_SYMLINK")
        for name in files:
            full = pathlib.Path(directory) / name
            st = os.lstat(full)
            require(stat.S_ISREG(st.st_mode) and st.st_nlink == 1)
            os.chmod(full, 0o555 if executable else 0o444)
        for name in dirs:
            require(not (pathlib.Path(directory) / name).is_symlink())
        os.chmod(directory, 0o555)


