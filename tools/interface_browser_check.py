def closure_components(rows):
    """Deterministic complete partition; component READ caps are independent."""
    require(type(rows) is list and 0 < len(rows) <= 8192, "BROWSER_CLOSURE_COUNT")
    names, chrome_total, non_chrome_total = [], 0, 0
    for row in rows:
        closed(row, ("path", "bytes", "sha256"))
        safe(row["path"])
        chrome = row["path"].startswith("chrome/")
        integer(row["bytes"], 0, 512 * 2**20 if chrome else 128 * 2**20)
        require(type(row["sha256"]) is str and HEX.fullmatch(row["sha256"]))
        closure_location(row["path"])  # Complete closed path classification.
        names.append(row["path"])
        if chrome:
            chrome_total += row["bytes"]
        else:
            non_chrome_total += row["bytes"]
    require(names == sorted(set(names)) and len({n.casefold() for n in names}) == len(names),
            "BROWSER_CLOSURE_UNIQUE_INVENTORY")
    require(chrome_total <= 512 * 2**20 and non_chrome_total <= 512 * 2**20,
            "BROWSER_CLOSURE_COMPONENT_READ_CAPS")
    chrome = [row for row in rows if row["path"].startswith("chrome/")]
    require(len(chrome) == 255 and chrome_total == 461618038, "BROWSER_COMPLETE_GOOGLE_COMPONENT")
    require({"path": "chrome/chrome", "bytes": 297798984, "sha256": CHROME_BINARY_SHA} in chrome,
            "BROWSER_GOOGLE_BINARY_PIN")
    return {"chrome_bytes": chrome_total, "non_chrome_bytes": non_chrome_total,
            "entries": len(rows)}


