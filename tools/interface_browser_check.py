def prep_unzip(raw):
    require(type(raw) is bytes and 0 < len(raw) <= 512 * 2**20, "PREPARATION_ZIP_BYTES")
    members, total = {}, 0
    with zipfile.ZipFile(io.BytesIO(raw)) as archive:
        require(0 < len(archive.infolist()) <= 1024, "PREPARATION_ZIP_COUNT")
        folded = set()
        for entry in archive.infolist():
            safe(entry.filename)
            mode = entry.external_attr >> 16
            require(not entry.is_dir() and not entry.flag_bits & 1
                    and (stat.S_IFMT(mode) == 0 or stat.S_ISREG(mode)), "PREPARATION_ZIP_MEMBER")
            require(entry.filename not in members and entry.filename.casefold() not in folded,
                    "PREPARATION_ZIP_ALIAS")
            folded.add(entry.filename.casefold())
            cap = 256 * 2**20 if entry.filename.startswith("archives/") or entry.filename == "runtime/runtime.tar" else (
                  32 * 2**20 if re.fullmatch(r"runtime/archives/dependency-[0-9]{4}\.tgz", entry.filename) else
                  2**20 if entry.filename.startswith(("sources/", "profiles/")) else 4 * 2**20)
            require(0 <= entry.file_size <= cap, "PREPARATION_ZIP_MEMBER_CAP")
            total += entry.file_size
            require(total <= 512 * 2**20, "PREPARATION_ZIP_TOTAL")
            with archive.open(entry) as stream:
                item = stream.read(entry.file_size + 1)
            require(len(item) == entry.file_size, "PREPARATION_ZIP_COMPLETE")
            members[entry.filename] = item
    return members


