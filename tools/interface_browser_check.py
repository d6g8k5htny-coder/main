    def observe_mount(self, record, label):
        mount = pathlib.Path(record["mount"])
        require(mount.parent == self.base and record["stage"] in ("work", "browser", "publication"))
        result = actual_run(["findmnt", "--json", "--mountpoint", str(mount)], 10, cap=65536)
        presence, mounted, capacity, device = "UNKNOWN", None, None, None
        try:
            mounted = os.path.ismount(mount)
            if result["status"] == 1 and result["raw"] in (b"", b"\n") and not mounted:
                presence = "ABSENT"
            elif result["status"] == 0 and result["raw"] is not None and mounted:
                native = strict(result["raw"])
                require(type(native.get("filesystems")) is list and len(native["filesystems"]) == 1
                        and native["filesystems"][0]["target"] == str(mount), "MOUNT_NATIVE_TARGET")
                capacity = os.statvfs(mount).f_blocks * os.statvfs(mount).f_frsize
                device, presence = os.stat(mount).st_dev, "PRESENT"
        except Exception:
            presence, capacity, device = "UNKNOWN", None, None
        value = {**META, "mount": str(mount), "presence": presence, "is_mount": mounted,
                 "reported_total_bytes": capacity, "device": device, "native_query_status": result["status"]}
        attempt = next(row for row in self.mount_attempts if row["stage"] == record["stage"])
        attempt["presence"], attempt["last_observation"] = presence, value
        if presence == "PRESENT":
            record["capacity_bytes"] = capacity
        return value, self.json("status/mount-" + record["stage"] + "-" + label + ".json", value)

    def volume(self, label, size_mib, execute):
        mount = self.base / label
        require(label in ("work", "browser", "publication") and
                all(row["stage"] != label for row in self.mount_attempts))
        attempt = {"stage": label, "mount": str(mount), "configured_capacity_bytes": size_mib * 2**20,
                   "mount_dispatch_attempted": False, "presence": "UNKNOWN", "last_observation": None}
        record = {"stage": label, "mount": str(mount), "capacity_bytes": None,
                  "mount_before": None, "mount_after": None}
        self.mount_attempts.append(attempt)
        self.volumes.append(record)  # BEFORE any owned path/filesystem/mount mutation.
        self.json("status/mount-" + label + "-intent.json", {**META, **attempt})
        mount.mkdir(mode=0o700)
        image = self.base / (label + ".img")
        with image.open("xb") as stream:
            stream.truncate(size_mib * 2**20)
        result = actual_run(["mkfs.ext4", "-F", str(image)], 30)
        self.retain(f"logs/filesystem-{label}-0.log", result["prefix"])
        require(result["status"] == 0 and result["raw"] is not None, "FILESYSTEM_SETUP")
        attempt["mount_dispatch_attempted"] = True
        result = actual_run(["sudo", "mount", "-o", "loop,nodev,nosuid" + ("" if execute else ",noexec"),
                             str(image), str(mount)], 30)
        self.retain(f"logs/filesystem-{label}-1.log", result["prefix"])
        observed, record["mount_before"] = self.observe_mount(record, "before")
        require(result["status"] == 0 and result["raw"] is not None and observed["presence"] == "PRESENT",
                "ACTUAL_MOUNT_UNCONFIRMED")
        require(type(record["capacity_bytes"]) is int and 0 < record["capacity_bytes"] <= size_mib * 2**20, "ACTUAL_CAPACITY")
        root = mount / "payload"
        root.mkdir(mode=0o700)
        result = actual_run(["sudo", "chown", "65532:65532", str(root)], 15)
        require(result["status"] == 0 and result["raw"] is not None, "PAYLOAD_OWNERSHIP")
        return root

