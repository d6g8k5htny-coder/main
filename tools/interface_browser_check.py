def prefix_observations(trace, end, a=0, b=0):
    """Independent actual finite partial-edge components, never candidate state."""
    values = [int(v) for v in trace["values"]]
    active, adjacency, immediate = set(), {}, {}
    def comp(v):
        if v not in active:
            return set()
        seen, todo = {v}, [v]
        while todo:
            for w in adjacency[todo.pop()]:
                if w not in seen:
                    seen.add(w)
                    todo.append(w)
        return seen
    def elder(vertices):
        return min(vertices, key=lambda v: (-values[v], v))
    positive = zero = 0
    for event in trace["events"][:end]:
        if event["kind"] == "activate":
            v = event["vertex"]
            active.add(v)
            adjacency[v] = set()
        elif event["kind"] == "merge":
            v, w = event["edge"]
            require(comp(v) != comp(w), "ORACLE_MERGE_CLASS")
            left, right = elder(comp(v)), elder(comp(w))
            survivor = min((left, right), key=lambda x: (-values[x], x))
            dying = right if survivor == left else left
            require((dying, survivor) == (event["dying"], event["survivor"]), "ORACLE_MERGE_PARENT")
            immediate[dying] = survivor
            adjacency[v].add(w)
            adjacency[w].add(v)
            if event["zero"]:
                zero += 1
            else:
                positive += 1
        else:
            v, w = event["edge"]
            require(comp(v) == comp(w), "ORACLE_NEUTRAL_CLASS")
    components = []
    for v in sorted(active):
        if not any(v in part for part in components):
            components.append(comp(v))
    return {"activeCount": len(active), "componentCount": len(components),
            "positiveCount": positive, "zeroCount": zero,
            "immediate_parent": immediate.get(a),
            "current_elder": elder(comp(a)) if a in active else None,
            "class_equal": (b in comp(a)) if a in active and b in active else False}


