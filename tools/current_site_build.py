def normalized_archive_bytes(name, raw):
    """Ignore only asset-release URL keys, which the existing site tool refreshes.

    Payload/meta and the complete source/evidence HTML remain exact. This is an
    admission comparison only: an existing accepted archive is never rewritten.
    """
    if name.endswith(".html"):
        return transform(raw.decode("utf-8"), ".html", without_release).encode("utf-8")
    return raw


def admit_existing_archive(directory, expected):
    if directory.is_symlink() or not directory.is_dir():
        raise ValueError("immutable snapshot destination is not a safe directory")
    actual = {}
    for path in directory.rglob("*"):
        if path.is_symlink():
            raise ValueError("immutable snapshot contains a symlink")
        if path.is_file():
            actual[path.relative_to(directory).as_posix()] = path
    if set(actual) != set(expected):
        raise ValueError("immutable snapshot membership conflict; no archive repair inferred")
    for name, content in expected.items():
        if normalized_archive_bytes(name, actual[name].read_bytes()) != content:
            raise ValueError(f"immutable snapshot content conflict: {name}")


def ensure_render_budget(data, meta):
    """Conservative pre-render bound for both static copies, without joining them.

    Repeated source disclosures, escaped metadata, indentation, edge rows and
    the complete inventory are counted before large per-node HTML allocation.
    """
    repeated = len(current_section(data, meta, prefix="../../../", search=False,
                                   snapshot_prefix="../", archived=True).encode()) + 6000
    graph = data["graph"]["data"]
    edge_cost = {node: 0 for node in graph["nodes"]}
    for edge in graph["edges"]:
        cost = 1500 + 16 * len(edge["relation"].encode())
        edge_cost[edge["from"]] += cost
        edge_cost[edge["to"]] += cost
    total_nodes = 0
    index_nodes = 0
    for node_id, node in graph["nodes"].items():
        stack = [(node, 0)]; values = 0
        while stack:
            value, depth = stack.pop(); values += 1
            if depth > 32:
                raise ValueError("pre-render metadata depth capacity exceeded")
            if isinstance(value, dict): stack.extend((v, depth + 1) for v in value.values())
            elif isinstance(value, list): stack.extend((v, depth + 1) for v in value)
        compact = len(json.dumps(node, ensure_ascii=False, separators=(",", ":")).encode())
        cost = repeated + 16 * compact + 64 * values + edge_cost[node_id]
        if cost > MAX_FILE_BYTES:
            raise ValueError("pre-render per-page capacity exceeded")
        total_nodes += cost
        index_nodes += 500 + 16 * (len(node_id.encode()) + len(str(node.get("kind", "")).encode())
                                  + len(str(node.get("classification", "")).encode()))
    inventory = sum(256 + len(escape(source_url(s)).encode()) + len(escape(s["path"]).encode())
                    for s in data["sources"])
    index = repeated + inventory + index_nodes + sum(3000 + 8 * len(e["text"].encode()) for e in data["equations"])
    if index > MAX_FILE_BYTES or 2 * (total_nodes + index + meta["bytes"] + 1024) > MAX_HISTORY_BYTES:
        raise ValueError("pre-render public history capacity exceeded")
    return 2 * (total_nodes + index + meta["bytes"] + 1024)


def build(site, payload):
    site = site.resolve()
    if not site.is_dir():
        raise ValueError("site must be an existing directory")
    if payload.stat().st_size > MAX_PAYLOAD:
        raise ValueError("current payload exceeds its admitted byte bound")
    raw = payload.read_bytes()
    data = validate_payload(parse_json(raw))
    fresh_meta = {"sha256": hashlib.sha256(raw).hexdigest(), "bytes": len(raw), "observed_at": data["observed_at"]}
    chosen = choose_archive(site, data)
    archive_id = chosen["id"] if chosen else mathematical_digest(data)
    meta = {**fresh_meta, "archive": archive_id}
    ensure_render_budget(data, meta)
    archive = None
    if not chosen:
        projection = mathematical_projection(data)
        projection_raw = manifest_bytes(projection)
        archive_meta = {"sha256": hashlib.sha256(projection_raw).hexdigest(), "bytes": len(projection_raw),
                        "observed_at": projection["observed_at"], "mathematical_sha256": archive_id, "archive_version": 2}
        ensure_render_budget(projection, archive_meta)
        archive = {"current.json": projection_raw, "current-meta.json": manifest_bytes(archive_meta),
                   **render_static_v2(projection, archive_meta, archived=True)}
    acquisition = project_current_acquisitions(data)
    aliases = render_live_current_v2(data, meta, acquisition=acquisition)
    planned, all_aliases, _ = manifest_plan(site, data, meta, raw, aliases, archive)
    capacity = planned["capacity"]
    capacity_html = (f'<p class="current-capacity">History capacity: {capacity["snapshots"]} of {capacity["maximum_snapshots"]} mathematical archives; '
                     f'{capacity["bytes"]} of {capacity["maximum_bytes"]} conservative retained bytes (including registry and release-key allowances). '
                     + ('Capacity warning: at least 75% of the archive or byte limit is used. Further versions will refuse publication at capacity; no history is pruned.'
                        if capacity["warning"] else 'Publication refuses additional versions at capacity; no history is pruned.') + '</p>')
    outputs = {"current.json": raw, "current-meta.json": manifest_bytes(meta), **all_aliases}
    pages = sorted(site.glob("*.html"))
    if not pages:
        raise ValueError("site has no main HTML pages")
    for page in pages:
        if page.is_symlink():
            raise ValueError("symlinked site page refused")
        original = page.read_bytes()
        if original.count(START) != 1 or original.count(END) != 1 or original.index(END) < original.index(START):
            raise ValueError(f"{page.name}: exactly one ordered CURRENT-SITE marker pair is required")
        start = original.index(START) + len(START)
        end = original.index(END)
        script_blocked = bool(re.search(
            rb"script-src\s+(?:&#39;|'|&apos;)none(?:&#39;|'|&apos;)", original))
        search_enabled = page.name not in ("research.html", "formal.html") and not script_blocked
        section = current_section(data, meta, search=search_enabled, acquisition=acquisition).replace("\n</section>", "\n" + capacity_html + "\n</section>").encode("utf-8")
        if page.name == "research.html":
            if script_blocked:
                raise ValueError("research.html: current freshness loader requires a script-enabled CSP")
            section = section.replace(
                b"\n</section>",
                b'\n<script type="module" src="current.mjs"></script>\n</section>')
        outputs[page.name] = original[:start] + b"\n" + section + b"\n" + original[end:]
    archive_relative = f'snapshots/{archive_id}'
    archive_outputs = ({f"{archive_relative}/{name}": content for name, content in archive.items()} if archive else {})
    outputs.update(archive_outputs)
    for name in outputs:
        target = site / name
        if target.is_dir() or any(parent.exists() and not parent.is_dir() for parent in target.parents
                                  if parent != site and parent.is_relative_to(site)):
            raise ValueError("unavailable generated file destination refused")
        if target.is_symlink() or any(parent.is_symlink() for parent in target.parents if parent != site and parent.is_relative_to(site)):
            raise ValueError("symlinked generated target refused")
    if (site / archive_relative).exists():
        if not chosen:
            admit_existing_archive(site / archive_relative, archive)
        for name in archive_outputs:
            del outputs[name]
    # Disappeared or renamed node convenience routes retain their last recorded
    # date and archive-bound neighbor/payload links. Never delete old evidence.
    if (site / "nodes").is_dir():
        for old in (site / "nodes").glob("*.html"):
            if old.is_symlink():
                raise ValueError("symlinked node page refused")
    # Rendering/admission are complete. Use same-directory replace for each file.
    for name, content in outputs.items():
        destination = site / name
        destination.parent.mkdir(parents=True, exist_ok=True)
        temporary = None
        try:
            with tempfile.NamedTemporaryFile(dir=destination.parent, prefix=".current-site-", delete=False) as stream:
                temporary = Path(stream.name)
                stream.write(content)
                stream.flush()
                os.fsync(stream.fileno())
            os.replace(temporary, destination)
            temporary = None
        finally:
            if temporary is not None:
                temporary.unlink(missing_ok=True)
    return {**meta, "pages": len(pages), "nodes": len(data["graph"]["data"]["nodes"]),
            "snapshot": archive_relative, "scientific_effect": "NONE"}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--payload", type=Path, required=True, help="exact admitted current.json bytes")
    parser.add_argument("--site", type=Path, default=Path(__file__).resolve().parents[1] / "docs/site")
    args = parser.parse_args(argv)
    try:
        result = build(args.site, args.payload)
    except (ValueError, OSError, TypeError, KeyError, RecursionError) as error:
        parser.exit(1, f"current site build refused: {error}\n")
    print(json.dumps(result, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
