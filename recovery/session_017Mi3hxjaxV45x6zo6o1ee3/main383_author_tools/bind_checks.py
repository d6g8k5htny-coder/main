"""Build the hosted-check table for main#383 head eb385803 and the patched PR body.

Usage: python3 -I bind_checks.py <checks_final.txt> <body_current.md> <out_dir>
Writes <out_dir>/comment.md and <out_dir>/body_new.md; prints a summary line.
Read-only on GitHub: posting/patching is done separately with gh api.
"""
import sys
from pathlib import Path

checks_path, body_path, out_dir = sys.argv[1], sys.argv[2], Path(sys.argv[3])
HEAD = "eb3858037abb510b24b0bfee19a328d1a9aef7ae"
lines = Path(checks_path).read_text().splitlines()
assert lines and lines[0].startswith("ALLDONE"), lines[:1]
rows = []
for ln in lines[1:]:
    if not ln.strip() or ln.startswith("20"):
        continue
    parts = ln.split(" ")
    # id name... status conclusion url started completed  (name may contain spaces)
    cid = parts[0]
    url = next(p for p in parts if p.startswith("https://"))
    i = parts.index(url)
    status, conclusion = parts[i - 2], parts[i - 1]
    name = " ".join(parts[1 : i - 2])
    completed = parts[i + 2] if len(parts) > i + 2 else ""
    run_id = url.split("/runs/")[1].split("/")[0]
    rows.append((name, status, conclusion, run_id, url, completed))
rows.sort()
all_success = all(r[1] == "completed" and r[2] == "success" for r in rows)
table = ["| check | status | conclusion | run | completed (UTC) |", "|---|---|---|---|---|"]
for name, status, conclusion, run_id, url, completed in rows:
    table.append(f"| `{name}` | {status} | {conclusion} | [{run_id}]({url}) | {completed} |")
table_md = "\n".join(table)
verdict = "all hosted checks concluded `success`" if all_success else "NOT all hosted checks succeeded; see table"
summary = (
    f"Hosted checks on head `{HEAD}`: {len(rows)} check runs, {verdict}."
)

comment = f"""**Hosted checks bound for main#383 head `{HEAD}` (main `9d51627e`, tree `049f1999`): {len(rows)} check runs, {verdict}.** Anthropic Claude, session `session_017Mi3hxjaxV45x6zo6o1ee3`. Organizational-independence credit 0. Scientific effect NONE.

{table_md}

- Head unchanged since the open note ([307/6134206640](https://github.com/d6g8k5htny-coder/main/issues/307#issuecomment-6134206640)); blobs `governance/OP-WORKFLOW-20260930.md` `68bb298eccdc9a8c2eb01bbbba1152c52044bd06` and `.github/pull_request_template.md` `dee09f0be067170b0cdea0c72a1097d7cca61f89`.
- Still needed before landing: a distinct source reader and a distinct integrator (activation [307/6134180947](https://github.com/d6g8k5htny-coder/main/issues/307#issuecomment-6134180947)). The author does not mark ready or merge; findings are answered with new commits only, never by rewriting history.

---
_Generated by [Claude Code](https://claude.ai/code)_
"""

body = Path(body_path).read_text()
old = "Hosted checks on the head are bound in a PR comment when they complete."
assert body.count(old) == 1, body.count(old)
new = (
    f"Hosted checks on the head: {len(rows)} check runs, {verdict} "
    f"(run table in the PR comment posted after completion). "
    + "; ".join(f"`{r[0]}` {r[2]} run {r[3]}" for r in rows)
    + "."
)
body_new = body.replace(old, new)
# Drop the title line the fetch script prepended, if present.
if body_new.startswith("TITLE:"):
    body_new = body_new.split("\n", 1)[1]
# Drop the duplicated trailing attribution line (server-side footer) so it is not stacked.
tail = "\n---\n_Generated by [Claude Code](https://claude.ai/code/session_017Mi3hxjaxV45x6zo6o1ee3)_"
if body_new.rstrip().endswith(tail.strip()):
    body_new = body_new.rstrip()[: -len(tail.strip())].rstrip() + "\n"
out_dir.mkdir(parents=True, exist_ok=True)
(out_dir / "comment.md").write_text(comment)
(out_dir / "body_new.md").write_text(body_new)
print(summary)
print("comment bytes", len(comment.encode()), "body bytes", len(body_new.encode()), "all_success", all_success)
