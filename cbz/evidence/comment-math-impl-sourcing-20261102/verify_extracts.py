#!/usr/bin/env python3
"""Verify the implementation-sourcing addendum to the comment-math census.

Read-only. Nothing in extracts/ is executed.

    python3 -I verify_extracts.py [--repo NAME=PATH ...] [--check]

checks that every file in extracts/ has the SHA-256 that MANIFEST.json records,
that every git carrier in SOURCING.json resolves (`git rev-parse COMMIT:PATH`
equals the recorded blob) in the clones given with --repo, as does every
committed_elsewhere carrier in MANIFEST.json, that SOURCING.json
only references extracts that exist, and that the recorded summary equals a
fresh count. Without --check it writes SOURCING.md; with --check it fails on
any difference from the committed SOURCING.md.

    python3 -I verify_extracts.py --live [--token-env GITHUB_TOKEN]

re-fetches every source comment through the GitHub REST API, checks the body
SHA-256 against the value recorded at extraction, and re-extracts each block by
its recorded character offsets, comparing it byte for byte with the committed
file. Comments edited after extraction are reported as drift, not as failures
of the extract.
"""
import argparse
import collections
import hashlib
import json
import os
import subprocess
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
MANIFEST = os.path.join(HERE, 'MANIFEST.json')
SOURCING = os.path.join(HERE, 'SOURCING.json')
REPORT = os.path.join(HERE, 'SOURCING.md')
ROLES = ('IMPLEMENTATION', 'PARTIAL')
RELAXED = 'identical_except_one_extra_final_newline_in_block'
OUTCOMES = ('INLINE_EXTRACTED', 'COMMITTED_ELSEWHERE', 'DRIVE_OR_DROPBOX_CANDIDATE', 'NOT_LOCATED')


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def gitblob(data):
    return hashlib.sha1(b'blob %d\0' % len(data) + data).hexdigest()


def git(path, *args):
    r = subprocess.run(['git', '-C', path, *args], capture_output=True, text=True)
    return r.stdout.strip() if r.returncode == 0 else None


def summarize(sourcing):
    rows = sourcing['rows']
    return {
        'rows': len(rows),
        'outcome': dict(sorted(collections.Counter(r['outcome'] for r in rows).items())),
        'extracts': sum(len(r['extracts']) for r in rows),
        'git_carriers': sum(len(r['git_carriers']) for r in rows),
        'store_candidates': sum(len(r['store_candidates']) for r in rows),
    }


def render(manifest, sourcing, summ):
    out = []
    w = out.append
    w('# Implementation sourcing for comment-delivered mathematics')
    w('')
    w('Generated by `verify_extracts.py` from `SOURCING.json` and `MANIFEST.json`. Do not edit by hand.')
    w('')
    w(sourcing['banner'])
    w('')
    w('## Totals')
    w('')
    w(f'- Rows (census gap list D): **{summ["rows"]}**.')
    w('- Outcome: ' + ', '.join(f'{k} {v}' for k, v in summ['outcome'].items()) + '.')
    w(f'- Extracted code files: {summ["extracts"]}. Git carriers found outside the census: {summ["git_carriers"]}. '
      f'Drive or Dropbox metadata candidates: {summ["store_candidates"]}.')
    w('')
    by_id = {e['id']: e for e in manifest['extracts']}
    for outcome in OUTCOMES:
        rows = [r for r in sourcing['rows'] if r['outcome'] == outcome]
        w(f'## {outcome} ({len(rows)})')
        w('')
        for r in rows:
            w(f'- `{r["key"]}`: [{r["comment"]}]({r["url"]}). {r["note"]}')
            for i in r['extracts']:
                e = by_id[i]
                w(f'  - `{e["file"]}`: {e["role"]}, {e["lines"]} lines, sha256 `{e["sha256"][:16]}`'
                  + (', matches a SHA-256 cited in the comment' if e['cited_sha_match'] else '') + f'. {e["implements"]}')
            for c in r['git_carriers']:
                w(f'  - {c["repo"]} `{c["commit"][:8]}`:`{c["path"]}` blob `{c["blob"][:8]}` ({c["role"]})')
            for s in r['store_candidates']:
                w(f'  - {s["store"]} `{s["id"]}`: {s["title"][:160]} ({s["match"]})')
        if not rows:
            w('- none')
        w('')
    w('## Limits')
    w('')
    for line in sourcing['limits']:
        w(f'- {line}')
    w('')
    return '\n'.join(out)


def offline(manifest, sourcing, repos, allow_missing):
    errors = []
    ids = set()
    unchecked = 0
    for e in manifest['extracts']:
        ids.add(e['id'])
        p = os.path.join(HERE, e['file'])
        if not os.path.isfile(p):
            errors.append(f'{e["file"]}: missing')
            continue
        data = open(p, 'rb').read()
        if sha256(data) != e['sha256']:
            errors.append(f'{e["file"]}: sha256 differs from MANIFEST')
        if e['role'] not in ROLES:
            errors.append(f'{e["file"]}: role {e["role"]} is not an extracted role')
        if gitblob(data) != e['git_blob']:
            errors.append(f'{e["file"]}: git blob differs from MANIFEST')
        for c in e['committed_elsewhere']:
            want = gitblob(data) if c['relation'] == 'identical' else gitblob(data[:-1]) if c['relation'] == RELAXED else None
            if want != c['blob']:
                errors.append(f'{e["file"]}: committed_elsewhere blob {c["blob"][:8]} does not match the extract ({c["relation"]})')
            path = repos.get(c['repo'])
            if path is None:
                unchecked += 1
            elif git(path, 'rev-parse', f'{c["commit"]}:{c["path"]}') != c['blob']:
                errors.append(f'{e["file"]}: {c["repo"]}:{c["commit"][:8]}:{c["path"]} does not resolve to {c["blob"]}')
    on_disk = {f for f in os.listdir(os.path.join(HERE, 'extracts'))} if os.path.isdir(os.path.join(HERE, 'extracts')) else set()
    listed = {os.path.basename(e['file']) for e in manifest['extracts']}
    for f in sorted(on_disk - listed):
        errors.append(f'extracts/{f}: not in MANIFEST')
    for r in sourcing['rows']:
        if r['outcome'] not in OUTCOMES:
            errors.append(f'{r["key"]}: unknown outcome {r["outcome"]}')
        for i in r['extracts']:
            if i not in ids:
                errors.append(f'{r["key"]}: extract id {i} not in MANIFEST')
        if r['outcome'] == 'INLINE_EXTRACTED' and not r['extracts']:
            errors.append(f'{r["key"]}: INLINE_EXTRACTED without extracts')
        if r['outcome'] == 'COMMITTED_ELSEWHERE' and not r['git_carriers']:
            errors.append(f'{r["key"]}: COMMITTED_ELSEWHERE without git carriers')
        if r['outcome'] == 'DRIVE_OR_DROPBOX_CANDIDATE' and not r['store_candidates']:
            errors.append(f'{r["key"]}: DRIVE_OR_DROPBOX_CANDIDATE without candidates')
        for c in r['git_carriers']:
            path = repos.get(c['repo'])
            if path is None:
                unchecked += 1
                continue
            got = git(path, 'rev-parse', f'{c["commit"]}:{c["path"]}')
            if got != c['blob']:
                errors.append(f'{r["key"]}: {c["repo"]}:{c["commit"][:8]}:{c["path"]} resolves to {got}, expected {c["blob"]}')
    if unchecked and not allow_missing:
        errors.append(f'{unchecked} git carriers need clones that were not supplied (use --repo or --allow-missing-repos)')
    if sourcing.get('summary') != summarize(sourcing):
        errors.append('recorded summary differs from a fresh count')
    return errors, unchecked


def live(manifest, token_env):
    token = os.environ.get(token_env, '')
    drift = bad = 0
    cache = {}
    for e in manifest['extracts']:
        if e['api_path'] not in cache:
            req = urllib.request.Request('https://api.github.com' + e['api_path'])
            req.add_header('Accept', 'application/vnd.github+json')
            if token:
                req.add_header('Authorization', f'Bearer {token}')
            try:
                cache[e['api_path']] = json.load(urllib.request.urlopen(req, timeout=30)).get('body') or ''
            except Exception as exc:
                cache[e['api_path']] = exc
        body = cache[e['api_path']]
        if isinstance(body, Exception):
            print(f'{e["comment"]}: UNREADABLE ({type(body).__name__})')
            drift += 1
            continue
        if sha256(body.encode('utf-8')) != e['body_sha256']:
            print(f'{e["comment"]}: comment edited since extraction')
            drift += 1
            continue
        if body[e['start']:e['end']].encode('utf-8') != open(os.path.join(HERE, e['file']), 'rb').read():
            print(f'{e["file"]}: re-extraction differs')
            bad += 1
    print(f'live: {drift} comments drifted or unreadable, {bad} extracts differ from re-extraction')
    return 1 if bad else 0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--repo', action='append', default=[], metavar='NAME=PATH')
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--allow-missing-repos', action='store_true')
    ap.add_argument('--live', action='store_true')
    ap.add_argument('--token-env', default='GITHUB_TOKEN')
    a = ap.parse_args()
    manifest = json.load(open(MANIFEST, encoding='utf-8'))
    sourcing = json.load(open(SOURCING, encoding='utf-8'))
    if a.live:
        return live(manifest, a.token_env)
    repos = dict(x.split('=', 1) for x in a.repo)
    errors, unchecked = offline(manifest, sourcing, repos, a.allow_missing_repos)
    text = render(manifest, sourcing, summarize(sourcing))
    if a.check:
        if not os.path.exists(REPORT) or open(REPORT, encoding='utf-8').read() != text:
            errors.append('SOURCING.md differs from a fresh render')
    else:
        open(REPORT, 'w', encoding='utf-8').write(text)
    for e in errors:
        print('FAIL', e)
    print(f'extracts {len(manifest["extracts"])}, rows {len(sourcing["rows"])}, unchecked carriers {unchecked}')
    if not errors:
        print('check: OK' if a.check else 'written: SOURCING.md')
    return 1 if errors else 0


if __name__ == '__main__':
    sys.exit(main())
