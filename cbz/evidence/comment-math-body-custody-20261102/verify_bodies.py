#!/usr/bin/env python3
"""Verify the comment-body custody bundle for the comment-math census.

Read-only. Nothing under sources/ is executed or parsed as code.

    python3 -I verify_bodies.py [--census PATH] [--check]

checks that every file in sources/ has the byte count, SHA-256 and git blob id
that MANIFEST.json records, that sources/ holds no unlisted file, and that the
recorded summary equals a fresh count. With --census it also checks each body
against the census JSON (main#745): the SHA-256 must equal the census
body_sha256 of that comment, and every INLINE_ONLY artifact must be covered.
Without --check it writes INDEX.md; with --check it fails on any difference
from the committed INDEX.md.

    python3 -I verify_bodies.py --live [--token-env GITHUB_TOKEN]

re-fetches every comment through the GitHub REST API and compares the current
body with the committed bytes. A comment edited or deleted since 31 October is
reported as drift, not as a failure of the copy.
"""
import argparse
import collections
import hashlib
import json
import os
import sys
import urllib.error
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
MANIFEST = os.path.join(HERE, 'MANIFEST.json')
INDEX = os.path.join(HERE, 'INDEX.md')


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def gitblob(data):
    return hashlib.sha1(b'blob %d\0' % len(data) + data).hexdigest()


def summarize(manifest):
    bodies = manifest['bodies']
    return {
        'bodies': len(bodies),
        'bytes': sum(b['bytes'] for b in bodies),
        'source': dict(sorted(collections.Counter(b['source'] for b in bodies).items())),
        'repo': dict(sorted(collections.Counter(b['comment'].split('#', 1)[0] for b in bodies).items())),
        'artifacts': len({k for b in bodies for k in b['census_keys']}),
    }


def render(manifest, summ):
    out = []
    w = out.append
    w('# Comment-body custody for the comment-math census')
    w('')
    w('Generated by `verify_bodies.py` from `MANIFEST.json`. Do not edit by hand.')
    w('')
    w(manifest['banner'])
    w('')
    w(f'- Bodies: **{summ["bodies"]}** ({", ".join(f"{k} {v}" for k, v in summ["source"].items())}), '
      f'{summ["bytes"]} bytes in all.')
    w(f'- Repositories: {", ".join(f"{k} {v}" for k, v in summ["repo"].items())}.')
    w(f'- Census artifacts covered: {summ["artifacts"]} of the {manifest["census"]["artifacts"]} with custody '
      f'`{manifest["census"]["custody_class"]}`.')
    w('')
    w('| Comment | Created | Bytes | SHA-256 | File | Census artifacts |')
    w('|---|---|---:|---|---|---|')
    for b in manifest['bodies']:
        keys = ', '.join(f'`{k}`' for k in b['census_keys'])
        w(f'| [{b["comment"]}]({b["url"]}) | {b["created"][:10]} | {b["bytes"]} | `{b["sha256"][:16]}` | '
          f'[`{os.path.basename(b["file"])}`]({b["file"]}) | {keys} |')
    w('')
    return '\n'.join(out)


def offline(manifest, census_path):
    errors = []
    for b in manifest['bodies']:
        p = os.path.join(HERE, b['file'])
        if not os.path.isfile(p):
            errors.append(f'{b["file"]}: missing')
            continue
        data = open(p, 'rb').read()
        if len(data) != b['bytes']:
            errors.append(f'{b["file"]}: {len(data)} bytes, MANIFEST records {b["bytes"]}')
        if sha256(data) != b['sha256']:
            errors.append(f'{b["file"]}: sha256 differs from MANIFEST')
        if gitblob(data) != b['git_blob']:
            errors.append(f'{b["file"]}: git blob differs from MANIFEST')
    src = os.path.join(HERE, 'sources')
    on_disk = set(os.listdir(src)) if os.path.isdir(src) else set()
    listed = [os.path.basename(b['file']) for b in manifest['bodies']]
    if len(listed) != len(set(listed)):
        errors.append('MANIFEST lists a file twice')
    for f in sorted(on_disk - set(listed)):
        errors.append(f'sources/{f}: not in MANIFEST')
    if manifest.get('summary') != summarize(manifest):
        errors.append('recorded summary differs from a fresh count')
    if census_path:
        census = json.load(open(census_path, encoding='utf-8'))
        recorded = {}
        want = set()
        for a in census['artifacts']:
            for v in a['versions']:
                recorded.setdefault(v['comment'], v['body_sha256'])
            if a['custody']['class'] == manifest['census']['custody_class']:
                want.add(a['key'])
        for b in manifest['bodies']:
            if recorded.get(b['comment']) != b['sha256']:
                errors.append(f'{b["comment"]}: sha256 differs from the census body_sha256')
        have = {k for b in manifest['bodies'] for k in b['census_keys']}
        for k in sorted(want - have):
            errors.append(f'census artifact {k} is not covered')
        for k in sorted(have - want):
            errors.append(f'census artifact {k} is not {manifest["census"]["custody_class"]}')
    return errors


def live(manifest, token_env):
    token = os.environ.get(token_env, '')
    same = drift = gone = 0
    for b in manifest['bodies']:
        req = urllib.request.Request('https://api.github.com' + b['api_path'])
        req.add_header('Accept', 'application/vnd.github+json')
        if token:
            req.add_header('Authorization', f'Bearer {token}')
        try:
            body = json.load(urllib.request.urlopen(req, timeout=30)).get('body') or ''
        except urllib.error.HTTPError as exc:
            print(f'{b["comment"]}: HTTP {exc.code}')
            gone += 1
            continue
        except Exception as exc:
            print(f'{b["comment"]}: UNREADABLE ({type(exc).__name__})')
            gone += 1
            continue
        if body.encode('utf-8') == open(os.path.join(HERE, b['file']), 'rb').read():
            same += 1
        else:
            print(f'{b["comment"]}: edited since 31 October')
            drift += 1
    print(f'live: {same} identical, {drift} edited, {gone} unreadable')
    return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--census', metavar='PATH')
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--live', action='store_true')
    ap.add_argument('--token-env', default='GITHUB_TOKEN')
    a = ap.parse_args()
    manifest = json.load(open(MANIFEST, encoding='utf-8'))
    if a.live:
        return live(manifest, a.token_env)
    errors = offline(manifest, a.census)
    text = render(manifest, summarize(manifest))
    if a.check:
        if not os.path.exists(INDEX) or open(INDEX, encoding='utf-8').read() != text:
            errors.append('INDEX.md differs from a fresh render')
    else:
        open(INDEX, 'w', encoding='utf-8').write(text)
    for e in errors:
        print('FAIL', e)
    print(f'bodies {len(manifest["bodies"])}' + (', census checked' if a.census else ', census not checked'))
    if not errors:
        print('check: OK' if a.check else 'written: INDEX.md')
    return 1 if errors else 0


if __name__ == '__main__':
    sys.exit(main())
